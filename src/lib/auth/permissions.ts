export function hasPermission(role: Role, permission: Permission): boolean {
  return ROLE_PERMISSIONS[role].includes(permission);
}

export function hasAnyPermission(role: Role, permissions: Permission[]): boolean {
  return permissions.some((permission) => hasPermission(role, permission));
}

export function hasAllPermissions(role: Role, permissions: Permission[]): boolean {
  return permissions.every((permission) => hasPermission(role, permission));
}

export function permissionsFor(role: Role): readonly Permission[] {
  return ROLE_PERMISSIONS[role];
}

/**
 * Determines whether a user may see records belonging to a mine.
 * Users scoped to specific mines/subsidiaries only see those records.
 */
export function canAccessMine(
  user: Pick<User, 'role' | 'mineIds' | 'subsidiaryIds'>,
  mineId: string,
  mineSubsidiaryId?: string,
): boolean {
  if (user.role === 'system_admin' || user.role === 'corporate_management' || user.role === 'regulatory_user') {
    return true;
  }
  if (user.mineIds.length > 0) return user.mineIds.includes(mineId);
  if (user.subsidiaryIds.length > 0 && mineSubsidiaryId) {
    return user.subsidiaryIds.includes(mineSubsidiaryId);
  }
  return true;
}

