export function permissionDeniedReason(permission: Permission): string {
  const labels: Partial<Record<Permission, string>> = {
    'compliance.verify': 'Compliance verification is restricted to compliance officers.',
    'compliance.create': 'Creating compliance requirements is restricted to compliance officers and administrators.',
    'inspection.review': 'Inspection review is restricted to mine managers and compliance officers.',
    'corrective_action.verify': 'Verifying corrective actions is restricted to the responsible reviewer.',
    'corrective_action.close': 'Closing corrective actions requires prior verification.',
    'workforce.view_personal': 'Personal workforce records are restricted by role.',
    'audit.export': 'Exporting the audit trail is restricted to authorised governance roles.',
    'admin.access': 'Administration is restricted to system administrators.',
  };
  return labels[permission] ?? 'Your role does not permit this action.';
}
